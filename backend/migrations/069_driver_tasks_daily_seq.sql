-- =====================================================================
-- 069_driver_tasks_daily_seq.sql
-- CRM v1.1 (сессия 2026-09-26) — правки формата карточки водителя после
-- теста Коммита 3: driver_tasks получает свой порядковый номер за день,
-- используя ТОТ ЖЕ атомарный счётчик driver_notification_daily_seq
-- (042_driver_notification_daily_seq.sql), которым уже нумеруется
-- driver-карточка при создании брони (buildDriverText() в
-- services/booking.js, поле "N.") — единая сквозная нумерация карточек за
-- день независимо от источника (сайт или ручное создание в
-- /internal/driver-tasks), как это реально ведётся у диспетчера.
-- Присваивается один раз при создании задачи (POST /driver-tasks), не
-- пересчитывается при повторных тестовых отправках.
-- =====================================================================

ALTER TABLE driver_tasks ADD COLUMN daily_seq SMALLINT;
COMMENT ON COLUMN driver_tasks.daily_seq IS 'Порядковый номер карточки за день — из driver_notification_daily_seq (042), тот же счётчик, что и у driver-карточки, создаваемой при бронировании с сайта. Присваивается один раз при создании задачи. НЕ путать с seq_label (свободный текст "N-"/"N+" для задач, вставленных вручную после публикации списка, — другое назначение, см. комментарий 042_driver_notification_daily_seq.sql).';
